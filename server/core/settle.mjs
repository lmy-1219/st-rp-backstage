// unanswered：〔当事人〕找过玩家、玩家一直没接的（waiting.mjs），也算进等回音；promises：〔当事人〕和别人约好、还没办的；here：玩家此刻在哪、身边有谁；around：别的有卡的人此刻在哪
// own：〔当事人〕是主角团的人，最新一份规划里写的〔当事人〕自己的打算 { want: 想干, next: 下一步 }（用户 10/12，N-363：角色没有自己的驱动，和没后台时一样——
// 不在场时按〔当事人〕的打算往前推一步，〔当事人〕下次露面带着结果来）
export function settlePrompt({ who, userName = '玩家', span = '', leaving = '', errands = [], waits = [], profile = '', tie = '', place = '', unanswered = [], promises = [], here = '', around = [], own = null }) {
    const mine = own && (own.want || own.next) ? [renderPronouns("【〔当事人〕自己惦记的事】（这阵子〔当事人〕自己想办成的、下一步要去做的；这段时间〔当事人〕会照着去办，写进\"打算\"）", { person: who }), ...(own.want ? [`· 想办成：${own.want}`] : []), ...(own.next ? [`· 下一步：${own.next}`] : [])] : [];
    return [
        `【在外头的人】${who}`,
        `【玩家角色】${userName}`,
        `【过了多久】${span || '不清楚过了多久'}`,
        leaving ? `【${personWord(who)}走前那两条】${leaving}` : '',
        profile ? `【${personWord(who)}的兴趣和习惯】${profile}` : '',
        tie ? `【${personWord(who)}和${userName}】${tie}` : '',
        place ? `【${personWord(who)}在哪】${place}` : '',
        '【去办（事账原文）】',
        ...errands.map(e => `· ${e.text ?? e}（${e.status ?? '排着'}）`),
        '【等回音（事账原文）】',
        ...waits.map(w => `· ${w.text}（等${(w.with ?? []).join('、') || '对方'}；${w.elapsed || w.why || '等了多久不清楚'}）`),
        ...mine,
        ...(unanswered.length ? [`【${personWord(who)}找过${userName}、还没人接】（也写进"等回音"，事名照这里的原文）`, ...unanswered.map(u => `· ${u.text}（${u.elapsed}；这是第 ${u.n} 回没人接）`)] : []),
        ...(promises.length ? [renderPronouns("【〔当事人〕和别人约好、还没办的】", { person: who }), ...promises.map(p => `· ${p}`)] : []),
        ...(here ? [`【${userName}此刻】${here}（${personWord(who)}不一定知道：找上门得是${personWord(who)}找得到的地方——${personWord(who)}知道${userName}去了哪儿、或者问得到；不知道就别写${personWord(who)}直接找到那儿）`] : []),
        ...(around.length ? ['【别的人此刻在哪】', ...around.map(a => `· ${a}`)] : []),
    ].filter(Boolean).join('\n');
}

export function parseSettle(text) {
    const s = String(text ?? '');
    const a = s.indexOf('{'), b = s.lastIndexOf('}');
    if (a < 0 || b <= a) return null;
    try {
        const v = JSON.parse(s.slice(a, b + 1));
        const str = (x, n = 200) => typeof x === 'string' ? x.trim().slice(0, n) : '';
        const rows = (xs, field, allowed) => (Array.isArray(xs) ? xs : []).filter(x => x && str(x.事) && allowed.includes(x[field])).map(x => ({ text: str(x.事, 1000), result: x[field], note: str(x.怎么回事) }));
        return {
            errands: rows(v.办到哪儿, '结果', ['办了', '没办成', '还在办']),
            waits: rows(v.等回音, '他', ['再联系', '上门', '放下', '还等']),
            contact: { way: ['消息', '电话', '上门', '不'].includes(v.联系?.方式) ? v.联系.方式 : '不', text: str(v.联系?.说什么) },
            // 顺带（用户 10/9）：他找上门的那地方约他的人正好在，顺便把约好的那件提前到眼下
            pull: str(v.顺带?.约定, 300) ? { promise: str(v.顺带.约定, 300), surface: str(v.顺带.露面, 300), respond: str(v.顺带.应答, 300) } : null,
            // 他按自己的打算办到哪（主角团的人，见 settlePrompt 的 own）
            own: ['办了', '没办成', '碰了钉子'].includes(v.打算?.结果) ? { result: v.打算.结果, note: str(v.打算?.怎么回事) } : null,
            home: str(v.住处, 60),
            mind: str(v.心里),
        };
    } catch { return null; }
}
