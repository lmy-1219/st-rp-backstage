// 此刻能做的（场记章程第二节第 5 条、B3，用户 10/10："我感觉是认知给角色卡得太死，该有的提示没做到，只做了不该做什么"）：
// 有卡的人那一格以前只有禁令（别回到这儿、别替对方想、看不见那头），没有"此刻能做什么"——隔着电话听见那头有别人，模型不敢写赶过来、问那是谁。
// 这里按他此刻的处境列几样可以做的，由他按自己的性子和眼前的场面挑。是材料不是剧本：只列能做的，不写该做什么，不写对方会怎样。
// 纯程序，不调模型；题材无关。只给有卡的人（旁白不给），放在"这一轮"那块、此刻的样子之后（slot.extrasFor）。
//
// status：'remote'（隔着电话、消息）／'arrived'（刚进场，头两回开口）／'present'（就在这儿）
// way：远程时是'电话'还是'消息'
// intent：他这回的来意还没说出口（matters.mjs 的 INTENT）；matters：他手上有没下文的事

export function optionsFor({ status = 'present', way = '', intent = false, matters = false, userName = '对方', name = '他' } = {}) {
    const head = where => `${name}此刻可以做的（${where}；做不做、做哪样，由${name}按自己的性子和眼前的场面定）：`;
    if (status === 'remote' && /电话/.test(way)) return [head('隔着电话'),
        '· 可以隔着电话接着问，也可以把自己那头的事说出来，也可以沉默听着',
        '· 可以挂了，也可以放下电话就过来',
        `· 听见${userName}那头有别人，可以问是谁，也可以装没听见`];
    if (status === 'remote') return [head('隔着消息'),
        '· 可以回，也可以先不回',
        '· 可以改打电话，也可以直接过来'];
    if (status === 'arrived') return [head('刚到'),
        intent ? '· 可以先把来意说出来，也可以先不说、看看情形' : '· 可以先说怎么来了，也可以先不说、看看情形',
        '· 可以问刚才那是谁、在干什么',
        '· 可以把自己那头的事提起来'];
    const hand = [intent && '来意', matters && '手上悬着的事'].filter(Boolean).join('、');
    return [head('就在这儿'),
        ...(hand ? [`· 可以提起${hand}，也可以先不提`] : []),
        '· 可以顺手干自己的事，也可以不接这句',
        '· 可以走'];
}
