const WORDS = [
    ['利用', '借着', '便福胜顺流水专权红盈营锋吉获净毛暴锐', '率'],
    ['弱点', '软处', '薄脆软虚衰削减示较', '儿头燃亮火灯着'],
    ['操纵', '摆弄', '', '杆台盘系装室面员性'],
    ['算计', '盘算', '预估计核清结换推盘运演折合打总决筹测验精速口笔珠', '划时器量数较算价费'],
    ['拿捏住', '摸透了', '', ''],   // 换词读着要顺（主窗 10/12："拿捏住她"换成"摸得准住她"不通）
    ['拿捏', '摸透', '', ''],
    ['手段', '办法', '', '位落'],
];
const esc = s => s.replace(/[.*+?^${}()|[\]\\]/g, '\\$&');
const RULES = WORDS.map(([word, to, before, after]) => ({
    re: new RegExp(`${before ? `(?<![${esc(before)}])` : ''}${esc(word)}${after ? `(?![${esc(after)}])` : ''}`, 'g'),
    to,
}));

export function warmWords(text) {
    if (text == null) return '';
    let s = String(text);
    for (const { re, to } of RULES) s = s.replace(re, to);
    return s;
}
