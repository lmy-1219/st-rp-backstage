export const intimatePair = people => JSON.stringify([...people].sort());
export function validateIntimateProgress(raw, lines, current = []) {
    const items = [], dropped = [], seen = new Set();
    if (raw === undefined) return { items, dropped };
    if (!Array.isArray(raw)) return { items, dropped: [{ reason: '亲密线进度须是数组' }] };
    for (const row of raw) {
        const people = row?.['谁和谁'], value = row?.现在, basis = row?.依据;
        const key = Array.isArray(people) && people.length === 2 && people.every(n => typeof n === 'string') && new Set(people).size === 2 ? intimatePair(people) : null;
        const line = key && lines.find(x => x.ok !== false && x.成年 === true && intimatePair(x.谁) === key);
        const previous = line && current.find(x => intimatePair(x['谁和谁']) === key);
        const at = previous?.现在 ?? line?.现在;
        const steps = line?.阶梯 ?? [];
        const valid = line && typeof value === 'string' && (value === line.现在 || steps.includes(value));
        const jumps = valid && value !== line.现在 && steps.indexOf(value) > steps.indexOf(at) + 1;
        const reason = !line ? '不是生效亲密线里的这一对' : seen.has(key) ? '同一对重复交回' : !valid ? '现在不在阶梯或开局原文里' : jumps ? '一次不能跳过一格' : typeof basis !== 'string' || !basis.trim() ? '缺少依据' : '';
        if (key) seen.add(key);
        if (reason) { dropped.push({ reason: `亲密线进度：${reason}` }); continue; }
        items.push({ 谁和谁: [...line.谁], 现在: value, 依据: basis.trim().slice(0, 300) });
    }
    return { items, dropped };
}

