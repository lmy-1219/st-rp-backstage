// 【玩家的角色】那一块（用户 10/12）：标题只写"脾气和喜好"——这一块给规划排谁会怎么待她，不当成可以拿来对付她的东西，标题和说明里不用"弱点"一类的字。
// 人设原文可能分行、带小标题：每行缩两格，免得被当成简报里的一块；{{user}} 换成她的名字
export const PERSONA_MAX = 1500;
export const PERSONA_TITLE = "【玩家的角色】〔玩家〕的脾气和喜好（玩家卡里写的；给你排谁会怎么待〔玩家〕用，原文）";
// 截到 max 字以内：落在最后一个句末（句号、问号、叹号、分号、省略号、换行）；句末离得太远（前一半里都没有）就硬截
export function clipSentences(text, max) {
    const s = String(text ?? '');
    if (s.length <= max) return s;
    const head = s.slice(0, max);
    const at = Math.max(...['。', '！', '？', '!', '?', '；', ';', '…', '\n'].map(c => head.lastIndexOf(c)));
    return at >= max / 2 ? head.slice(0, at + 1).trimEnd() : head;
}
export function personaLines(p, { setup = null } = {}) {
    const name = String(p?.name ?? '').trim();
    const raw = String(p?.text ?? '').replace(/\{\{user\}\}/gi, name || playerWord({ setup, name })).replace(/\r/g, '').replace(/\n{3,}/g, '\n\n').trim();
    if (!raw) return [];
    const text = clipSentences(raw, PERSONA_MAX);
    return ['', renderPronouns(PERSONA_TITLE, { setup, name }), ...(name ? [`  名字：${name}`] : []), ...text.split('\n').map(l => `  ${l}`.trimEnd()),
        ...(text.length < raw.length ? ['  （后面太长，略去了）'] : [])];
}
const clip = (t, n) => { const s = String(t ?? '').replace(/\s+/g, ' ').trim(); return s.length > n ? `${s.slice(0, n)}…` : s; };

