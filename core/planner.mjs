// 一件事的"类别"撑没撑到开局单里的某一样：写的里头有它（"甲类、乙类"撑两样），或者写的是它的一截（两个字以上）
const catParts = cat => String(cat ?? '').split(/[、，,／/|｜;；\s]+/).map(x => x.trim()).filter(Boolean);
export const coversCategory = (cat, c) => {
    const want = String(c ?? '').trim(), got = String(cat ?? '').trim();
    return !!want && !!got && (got.includes(want) || catParts(got).some(p => p.length >= 2 && want.includes(p)));
};
const categoryList = categories => [...new Set((Array.isArray(categories) ? categories : []).map(c => String(c ?? '').trim()).filter(Boolean))];
// 开局单里这一份一件都没撑到的类别（parsePlan 记提醒用）
export const missedCategories = (items, categories = []) => categoryList(categories).filter(c => !(items ?? []).some(i => coversCategory(i.category, c)));
// 最近两份规划里各类别排了几件：[{ which: 上一份｜再上一份, counts: [[类别, 件数]], other: 写了类别、但不是开局单里的那几件 }]。
// 没有开局单类别不给；一件都没写类别的那份（有这一格以前的旧规划）不列——列出来全是 0，是假的
export function categoryCounts(plans, categories = []) {
    const cats = categoryList(categories);
    if (!cats.length) return [];
    return (plans ?? []).slice(0, 2).map((p, i) => ({ which: i ? '再上一份' : '上一份', items: (p?.items ?? []).filter(m => String(m?.category ?? '').trim()) }))
        .filter(p => p.items.length)
        .map(p => ({ which: p.which, counts: cats.map(c => [c, p.items.filter(m => coversCategory(m.category, c)).length]),
            other: p.items.filter(m => !cats.some(c => coversCategory(m.category, c))).length }));
}
// 字的二元组：只在连着的字里取（标点、空格断开）
const wordRuns = t => String(t ?? '').match(/[\p{L}\p{N}]+/gu) ?? [];
const charPairs = t => new Set(wordRuns(t).flatMap(w => { const c = [...w]; return c.slice(0, -1).map((x, i) => x + c[i + 1]); }));
const jaccard = (a, b) => {
    const x = charPairs(a), y = charPairs(b);
    if (!x.size || !y.size) return 0;
    let n = 0;
    for (const w of x) if (y.has(w)) n++;
    return n / (x.size + y.size - n);
};
const namesIn = (t, names) => [...new Set(names)].filter(n => n && String(t ?? '').includes(n)).sort();
// 同一条线：名字一样；去掉标点后一个包含另一个（短的至少两个字）；或者字的二元组重合（Jaccard）≥ 0.5——
// 后一种两边点到的名册里的人得一样（"甲的活计""乙的活计"二元组重合一半，却是两条线）
export function sameLine(a, b, names = []) {
    const x = wordRuns(a).join(''), y = wordRuns(b).join('');
    if (!x || !y) return false;
    if (x === y) return true;
    const [short, long] = x.length <= y.length ? [x, y] : [y, x];
    if (short.length >= 2 && long.includes(short)) return true;
    if (namesIn(x, names).join('\u0000') !== namesIn(y, names).join('\u0000')) return false;
    return jaccard(x, y) >= 0.5;
}
// "往后"里同一件：字的二元组 Jaccard ≥ 0.3；或者两句都点到两个以上同样的名册里的人、名字以外还有一个同样的二字词
export function sameAhead(a, b, names = []) {
    if (jaccard(a, b) >= 0.3) return true;
    if (namesIn(a, names).filter(n => String(b ?? '').includes(n)).length < 2) return false;
    const strip = t => [...names].filter(Boolean).sort((p, q) => q.length - p.length).reduce((s, n) => s.split(n).join(' '), String(t ?? ''));
    const y = charPairs(strip(b));
    return [...charPairs(strip(a))].some(w => y.has(w) && !weakPair(w));
}
// 拖着的线：上一份里的每条线，往回一份一份找同一条（接着上一份认出的那个名字比，名字慢慢变了也跟得上），连着几份；
// 到 DRAG_PLANS 份的列出来：[{ name: 上一份里的线名, n: 连着几份 }]
export function draggingLines(plans, { names = [] } = {}) {
    const recent = (plans ?? []).slice(0, LOOKBACK_PLANS).map(p => (Array.isArray(p?.node?.线) ? p.node.线 : []).map(l => String(l?.名 ?? '').trim()).filter(Boolean));
    const out = [];
    for (const name of recent[0] ?? []) {
        let cur = name, n = 1;
        for (const lines of recent.slice(1)) {
            const hit = lines.find(l => sameLine(cur, l, names));
            if (!hit) break;
            cur = hit;
            n++;
        }
        if (n >= DRAG_PLANS && !out.some(o => sameLine(o.name, name, names))) out.push({ name, n });
    }
    return out;
}
// 该来的还没来：上一份"往后"里的每一句，往回看几份里有几份写过同一件（不必连着：中间一份漏写了也是还没来）；
// 到 AHEAD_PLANS 份的列出来，写得最久的在前，至多 AHEAD_MAX 条：[{ text: 上一份那一句, n: 写了几份 }]
export function overdueAhead(plans, { names = [] } = {}) {
    const recent = (plans ?? []).slice(0, LOOKBACK_PLANS).map(p => (Array.isArray(p?.node?.往后) ? p.node.往后 : []).map(x => String(x ?? '').trim()).filter(Boolean));
    const out = [];
    for (const text of recent[0] ?? []) {
        const seen = [text];
        for (const list of recent.slice(1)) {
            const hit = list.find(x => seen.some(g => sameAhead(g, x, names)));
            if (hit) seen.push(hit);
        }
        if (seen.length >= AHEAD_PLANS && !out.some(o => sameAhead(o.text, text, names))) out.push({ text, n: seen.length });
    }
    return out.sort((a, b) => b.n - a.n).slice(0, AHEAD_MAX);
}

// 账本要事（规划简报"这一局到现在"）：做、改变、了结、时间、钱，按剧情日分组；太多时先略去早先的零碎（做、短暂的改变），
// 会持续的改变、了结、时间、钱都留着。dayOf(位置)→剧情日，when(日差)→"昨天"之类。
export const DIGEST_TYPES = new Set(['做', '改变', '了结', '时间', '钱', '关系']);
// 必留的：改变（会持续的）、了结、时间、钱、关系；做的、短暂的改变是零碎事
const mustKeep = r => r.type !== '做' && !(r.type === '改变' && !LASTING.includes(r.duration));
export function storyDigest(records, { dayOf, today, when, max = 220 }) {
    let keep = records.filter(r => DIGEST_TYPES.has(r.type));
    let cut = 0;
    if (keep.length > max) {
        const essential = keep.filter(mustKeep), minor = keep.filter(r => !mustKeep(r));
        const room = Math.max(0, max - essential.length);
        cut = minor.length - room;
        keep = [...essential, ...minor.slice(minor.length - room)].sort((a, b) => a.pos - b.pos || a.id - b.id);
    }
    const days = new Map();
    for (const r of keep) {
        const d = dayOf(r.pos);
        if (!days.has(d)) days.set(d, []);
        days.get(d).push(r);
    }
    return { days: [...days].map(([day, items]) => ({ day, when: when(today - day), items })), cut };
}

