export function purposeOf(v) {
    const s = typeof v === 'string' ? v.trim() : '';
    if (PURPOSES.includes(s)) return s;
    return /主线/.test(s) ? '主线' : /关系|两人|亲近/.test(s) ? '关系' : /意外|惊喜|变故/.test(s) ? '意外' : /氛围|日常|生活/.test(s) ? '氛围' : /^主/.test(s) ? '主线' : '';
}
// 知情、来由里"某人不知道……"那半句删掉（章程 H5：不知道的事一写出来，就把它交给了前台）：从那半句起头删到句号、分号、换行；
// 前面剩下的逗号去掉，连着的句末留最后一个。整格只剩这类句子就成了空的
const UNKNOWN_CLAUSE = /(?<=^|[，,。；;！!？?\n])[^，,。；;！!？?\n]*?(?:不知道|不知情|不晓得|蒙在鼓里)[^。；;\n]*/g;
export const stripUnknown = text => String(text ?? '').replace(UNKNOWN_CLAUSE, '')
    .replace(/[，,]+(?=[。；;\n]|$)/g, '').replace(/[。；;]+(?=[。；;])/g, '').replace(/^[，,。；;\s]+/, '').trim();
// 应答超过 120 字（章程 H5：提示词要至多 60 字，有的写到两倍）：截到 120 字以内最后一个句末；一个句末都没有就硬截
export const RESPOND_MAX = 120;
export function clipRespond(text) {
    const s = String(text ?? '');
    if (s.length <= RESPOND_MAX) return s;
    const head = s.slice(0, RESPOND_MAX);
    const at = Math.max(...['。', '！', '？', '!', '?'].map(c => head.lastIndexOf(c)));
    if (at < 0) return head;
    return s.slice(0, at + 1 + (/^[”」』"]/.test(s.slice(at + 1)) && at + 1 < RESPOND_MAX ? 1 : 0));
}
export function triggerOf(v) {
    const t = x => (typeof x === 'string' ? x.trim().slice(0, 120) : '');
    let out = {};
    if (v && typeof v === 'object' && !Array.isArray(v)) out = { scene: t(v['场景']), goal: t(v['目标']), time: t(v['时间']) };
    else if (Array.isArray(v)) for (const x of v) Object.entries(triggerOf(x) ?? {}).forEach(([k, val]) => { if (val && !out[k]) out[k] = val; });
    else if (t(v)) out = TIME_TEXT.test(t(v)) && !/镜头|在场/.test(t(v)) ? { time: t(v) } : /办成|没办成|之后|以后/.test(t(v)) ? { goal: t(v) } : { scene: t(v) };
    out = Object.fromEntries(Object.entries(out).filter(([, val]) => val));
    return Object.keys(out).length ? out : null;
}
// "只在那场戏"跟着什么：写了"人：／地方：／时间："就照写的；没写按字面猜——有名册里的名字算人，有时间词算时间，别的算地方
function sceneTtl(v, names = []) {
    const t = x => (typeof x === 'string' ? x.trim().slice(0, 60) : '');
    if (v && typeof v === 'object' && !Array.isArray(v)) {
        const k = ['人', '地方', '时间'].find(k => t(v[k]));
        if (k) return { kind: SCENE_TTL, follow: k, what: t(v[k]) };
        const f = ['人', '地方', '时间'].find(k => t(v['跟着']).includes(k));
        return { kind: SCENE_TTL, follow: f ?? '地方', what: t(v['是'] ?? v['什么']) };
    }
    const s = t(v).replace(/^跟着/, '');
    const m = s.match(/^(人|地方|时间)[：:\s]*(.*)$/);
    if (m) return { kind: SCENE_TTL, follow: m[1], what: m[2].trim() };
    const follow = names.some(n => n && (s === n || (n.length >= 2 && s.includes(n)))) ? '人' : TIME_TEXT.test(s) ? '时间' : '地方';
    return { kind: SCENE_TTL, follow, what: s };
}
export function ttlFrom(v, names = []) {
    if (v && typeof v === 'object' && !Array.isArray(v)) {
        const k = Object.keys(v).find(k => /那场戏/.test(k));
        if (k) return sceneTtl(v[k], names);
        const kind = TTL_KINDS.find(x => Object.keys(v).includes(x));
        return kind ? { kind } : null;
    }
    const s = typeof v === 'string' ? v.trim() : '';
    if (!s) return null;
    if (/那场戏/.test(s)) return sceneTtl(s.replace(/^.*?那场戏[：:，,\s]*/, ''), names);
    if (/一直/.test(s)) return { kind: '一直' };
    if (/三天/.test(s)) return { kind: '三天内' };
    if (/当天|今天|这一天/.test(s)) return { kind: '当天' };
    return null;
}

