// firm：记下的日子（不算还没记账的几条里临时认的跳转）。沉底回不来，只按它算；进不进口袋按眼下的日子。
// hold（N-268、D-140：场面 > 约定 > 口袋）：今天有说好的事、还没到办完的时候——和它无关的先不进口袋，口袋里的也先不沉；
