//   该来的还没来——"往后"里同一件写了三份以上（上一份还在写），点名这一份排它的第一步。
// 都是纯函数；plans 是最近的几份规划，新的在前：[{ node: { 线, 往后 }, items: [{ category }] }]。
export const DRAG_PLANS = 3;     // 同一条线连着几份算拖着
export const AHEAD_PLANS = 3;    // "往后"里同一件写了几份算该来没来
export const AHEAD_MAX = 4;      // 该来的还没来至多列几条
