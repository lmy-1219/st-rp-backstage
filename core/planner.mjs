export function turnWorth({ ideas = [], others = [], changes = [], acts = [], outside = [], lastPos = 0, actsAt = null, every = TURN_ACTS_EVERY } = {}) {
    if (others.length || changes.length || outside.length) return { worth: true, why: others.length ? '角色起了新念头' : changes.length ? '关系、持续的改变' : '镜头外有动向' };
    if (ideas.some(r => r.type === '想法' || TURN_CUE.test(String(r.text ?? '')) || (r.quotes ?? []).some(q => TURN_CUE.test(String(q))))) return { worth: true, why: '玩家拿主意的话' };
    const loud = acts.filter(r => LOUD_CUE.test(String(r.text ?? '')));
    if (!loud.length) return { worth: false, why: ideas.length ? '玩家随口说的，没有拿主意的字眼' : acts.length ? '做的事里没有闹大的字眼' : '没有新的' };
    if (Number.isFinite(Number(actsAt)) && lastPos - Number(actsAt) < every) return { worth: false, why: `只因做的事而问的才隔了 ${lastPos - Number(actsAt)} 条（要隔够 ${every} 条）` };
    return { worth: true, why: '做的事里有闹大的字眼', actsOnly: true };
}

