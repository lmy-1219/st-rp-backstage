// "这一局到现在"分三层（章程 H4；只在简报超了预算时用）。格＝这一局的单位（dayOf 数出来的就是这一局的格：天尺度是天，年尺度是年）。
//   最近 recent 格：账本要事逐条（和以前一样）；
//   再往前到上一个节点开始（nodeStart，那一格）为止：按场次经过给，一场一行；没写经过的那几条退回逐条，但只给必留的；
//   更早的不列（看【之前的节点】）。
// 一直算数的改变不按远近，单列一块（lasting）：去重，只留还成立的。
export function storyLayers(records, { dayOf, today, when, recent, nodeStart = -Infinity, episodes = [], max = 220 }) {
    const lastingChange = r => r.type === '改变' && LASTING.includes(r.duration);
    const from = today - Math.max(1, recent) + 1;
    const rest = records.filter(r => DIGEST_TYPES.has(r.type) && !lastingChange(r));
    const near = storyDigest(rest.filter(r => dayOf(r.pos) >= from), { dayOf, today, when, max }).days;
    const covered = r => episodes.some(e => r.pos >= e.from_pos && r.pos <= e.to_pos);
    const scenes = episodes.filter(e => String(e.text ?? '').trim() && dayOf(e.from_pos) < from && dayOf(e.to_pos) >= nodeStart)
        .map(e => ({ scene: true, pos: e.from_pos, day: Math.max(dayOf(e.from_pos), nodeStart), place: String(e.place ?? '').trim(), text: clip(e.text, SCENE_LINE) }));
    const loose = rest.filter(r => { const d = dayOf(r.pos); return d >= nodeStart && d < from && mustKeep(r) && !covered(r); }).map(r => ({ ...r, day: dayOf(r.pos) }));
    const mid = new Map();
    for (const x of [...scenes, ...loose].sort((a, b) => a.pos - b.pos)) { if (!mid.has(x.day)) mid.set(x.day, []); mid.get(x.day).push(x); }
    const days = [...[...mid].sort((a, b) => a[0] - b[0]).map(([day, items]) => ({ day, when: when(today - day), items })), ...near];
    const lasting = stillStanding(records.filter(lastingChange)).map(r => ({ ...r, when: when(today - dayOf(r.pos)) }));
    return { days, lasting };
}
// 一直算数的改变里还成立的：了结了的不要；同一人同一句只留一条；同一人同一类生活状况（住处……）只留最晚的
export function stillStanding(list) {
    const byKey = new Map();
    for (const r of [...list].sort((a, b) => a.pos - b.pos || a.id - b.id)) {
        if (r.closed_by) continue;
        const who = r.holder_name ?? r.holder;
        byKey.set(r.life?.kind ? `life\u0000${r.life.who ?? who}\u0000${r.life.kind}` : `text\u0000${who}\u0000${String(r.text ?? '').trim()}`, r);
    }
    return [...byKey.values()].sort((a, b) => a.pos - b.pos || a.id - b.id);
}
